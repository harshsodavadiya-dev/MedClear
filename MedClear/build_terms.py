terms_out = {}
for term, meaning, analogy, category, abbr, swap in TERMS:
    key = term if abbr else term.lower()
    if term in KEEP_NAME and term.lower() not in swap.lower():
        swap = f"{swap} ({term})"
    if key in terms_out:
        raise SystemExit(f"Duplicate term: {key}")
    entry = {"plain": meaning, "analogy": analogy, "category": category, "swap": swap}
    if abbr:
        entry["abbr"] = True
    terms_out[key] = entry

with open("terms.json", "w", encoding="utf-8") as f:
    json.dump(terms_out, f, indent=2, ensure_ascii=False)

